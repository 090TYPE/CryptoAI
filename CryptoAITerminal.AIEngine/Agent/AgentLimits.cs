namespace CryptoAITerminal.AIEngine.Agent;

/// <summary>
/// Общие пределы обоих агентских циклов.
///
/// В одном месте, потому что раньше это были два одинаковых литерала в двух файлах — а расходиться
/// им нельзя: сервер назначает функции <c>agent</c> одну модель и один потолок независимо от того,
/// какой из циклов её вызвал.
/// </summary>
public static class AgentLimits
{
    /// <summary>
    /// Длина одного хода модели.
    ///
    /// Было 1024, и этого не хватало именно здесь: копилот получает указание отвечать на языке
    /// вопроса, а кириллица стоит вдвое-втрое дороже латиницы, так что русский ответ упирался в
    /// предел regularly. Обрыв при этом приходил тем же путём, что и нормальное завершение, и
    /// показывался как готовый ответ.
    ///
    /// Потолок не оплачивается: модель останавливается сама, когда сказала всё. Оплачивается
    /// обрезанный ответ, который нельзя использовать.
    /// </summary>
    public const int MaxTokensPerTurn = 4096;
}
